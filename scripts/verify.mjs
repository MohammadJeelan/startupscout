import fs from 'fs';
import { chromium } from 'playwright-core';
const BASE = process.env.BASE || 'http://127.0.0.1:4175';
const b = await chromium.launch(); const p = await b.newPage({ viewport: { width: 1440, height: 900 } });
const errs = []; p.on('pageerror', (e) => errs.push(e.message)); p.on('console', (m) => m.type() === 'error' && errs.push(m.text()));
const ok = (m) => console.log('OK  ' + m); const fail = (m) => { console.log('FAIL ' + m); process.exitCode = 1; };
await p.goto(BASE + '/'); await p.waitForSelector('.card');
const n = await p.locator('.card').count(); n >= 45 ? ok(`${n} cards`) : fail('cards ' + n);
await p.screenshot({ path: 'shots/01-directory.png' });
await p.keyboard.press('/'); await p.waitForTimeout(150); await p.keyboard.type('security'); await p.waitForTimeout(300); ok('search security → ' + (await p.locator('.card').count()));
await p.keyboard.press('Escape'); await p.fill('input[type=search]', '');
await p.locator('.chips button', { hasText: 'Fintech' }).click(); const f = await p.locator('.card').count(); f > 0 ? ok(`Fintech filter → ${f}`) : fail('tag filter');
await p.screenshot({ path: 'shots/02-filtered-fintech.png' });
await p.locator('.card .star').first().click(); await p.locator('.cardlink').first().click(); await p.waitForSelector('.profile');
ok('profile ' + (await p.locator('.phead h1').innerText()) + ', ' + (await p.locator('table.fields tbody tr').count()) + ' field rows');
await p.fill('textarea', 'Ask a junior engineer for a referral'); await p.screenshot({ path: 'shots/03-profile.png', fullPage: true });
await p.keyboard.press('Escape'); await p.keyboard.press('g'); await p.waitForSelector('.funnel'); ok('insights: ' + (await p.locator('.funnel').innerText()).replace(/\s+/g, ' '));
await p.screenshot({ path: 'shots/04-insights.png', fullPage: true });
await p.reload(); await p.waitForSelector('.funnel'); await p.keyboard.press('s'); await p.waitForSelector('.lhead'); (await p.locator('.card').count()) === 1 ? ok('shortlist persisted') : fail('shortlist');
const [dl] = await Promise.all([p.waitForEvent('download'), p.getByRole('button', { name: /Export shortlist CSV/i }).click()]); ok('export ' + dl.suggestedFilename());
await p.keyboard.press('c'); await p.waitForSelector('text=Collect your own data'); ok('collect page');
await p.fill('input[aria-label="Seed company name"]', 'DemoCo');
await p.fill('input[aria-label="Seed URL"]', 'https://example.com');
await p.getByRole('button', { name: 'Add seed' }).click();
await p.waitForSelector('text=DemoCo');
const [seedDl] = await Promise.all([p.waitForEvent('download'), p.getByRole('button', { name: /Download my-seeds.csv/i }).click()]);
ok('seeds csv ' + seedDl.suggestedFilename());
// import a tiny startups-shaped JSON
const tiny = JSON.stringify([{ name: 'ImportCo', seed_url: 'https://import.example', status: 'ok', error: '', scraped_at: '2026-10-20T00:00:00Z', domain: 'import.example', final_url: 'https://import.example', title: 'ImportCo AI', description: 'fintech payments', og_site_name: '', careers_url: '', linkedin: '', twitter: '', github: '', youtube: '', instagram: '', public_emails: '', site_generator: '', sources: {}, tags_derived: ['Fintech'], completeness: 0.2 }]);
fs.writeFileSync('/tmp/ss-import.json', tiny);
await p.setInputFiles('input[type=file]', '/tmp/ss-import.json');
await p.waitForSelector('text=Loaded 1 companies', { timeout: 10000 });
ok('import message');
await p.goto(BASE + '/#/');
await p.waitForSelector('text=ImportCo');
ok('imported JSON directory');
await p.goto(BASE + '/#/collect');
await p.getByRole('button', { name: /Reload bundled dataset/i }).click();
await p.waitForSelector('text=Reloaded bundled');
await p.goto(BASE + '/#/');
await p.waitForSelector('.card');
const n2 = await p.locator('.card').count();
n2 >= 45 ? ok('reloaded bundled ' + n2) : fail('reload ' + n2);
await p.goto(BASE + '/#/c/does-not-exist'); await p.waitForSelector('text=No company at this address'); ok('404 state');
await p.route('**/startups.json', (r) => r.fulfill({ status: 500 })); await p.goto(BASE + '/#/'); await p.reload(); await p.waitForSelector('text=Couldn\'t load'); ok('error state'); await p.unroute('**/startups.json');
await p.screenshot({ path: 'shots/06-error-state.png' });
const m = await b.newPage({ viewport: { width: 390, height: 844 }, isMobile: true }); await m.goto(BASE + '/'); await m.waitForSelector('.card'); await m.screenshot({ path: 'shots/05-mobile.png' });
const real = errs.filter((e) => !/500|Failed to load resource/.test(e)); real.length ? fail(real.join(' | ')) : ok('no console errors');
await b.close();
